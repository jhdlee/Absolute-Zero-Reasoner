# Analysis scripts for Absolute Zero Reasoner
# These scripts are used for research analysis on uncertainty quantification
# and adaptive verification for self-evolving reasoning systems.
#
# Modules:
# - generate_tasks.py: Task generation with dual labels (execution vs LLM) and UQ metrics
# - analyze_uncertainty.py: AUROC analysis for evaluating UQ methods
# - diversity_sampling.py: Diversity-aware sampling with embeddings and DPP
# - adaptive_reward_manager.py: Reward manager with 3 verification modes
# - train_with_verification.py: Training script for comparing verification strategies
# - compare_verification_modes.py: Analysis and visualization of verification comparison
#
# Shell scripts:
# - run_pipeline.sh: Run the full UQ analysis pipeline
# - run_verification_experiments.sh: Run verification mode comparison experiments
